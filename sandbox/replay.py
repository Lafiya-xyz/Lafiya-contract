#!/usr/bin/env python3
"""Turn a window of recorded chain events into a local sandbox scenario.

  replay.py --events events.jsonl --from 1100 --to 2100 [--attesters map.json] > replay.toml
  cargo xtask sandbox up     --scenario replay.toml     # replay the window
  cargo xtask sandbox verify --scenario replay.toml     # diff vs recorded final state

Input is the JSONL from `lafiya-watchdog export` (same as the dashboard). Events
are applied in (ledger, tx_hash) order, so the output is byte-for-byte
reproducible. `verify` exits 1 and lists every difference between the replayed
chain and the recorded final state. See README.md ("Replay") for the sources of
non-determinism.
"""

import argparse
import json
import re
import sys


def load_window(path, lo, hi):
    with open(path, encoding="utf-8") as f:
        events = [json.loads(line) for line in f if line.strip()]
    events = [e for e in events if lo <= e["ledger"] < hi]
    return sorted(events, key=lambda e: (e["ledger"], e.get("tx_hash") or ""))


def name_of(address):
    return "a-" + re.sub(r"[^a-z0-9]", "", address.lower())[:12]


def build(events, regions):
    attesters, status = {}, {}
    history, order, revoked = {}, [], set()

    def ensure(addr):
        attesters.setdefault(addr, regions.get(addr))
        status.setdefault(addr, "active")

    for e in events:
        topics, name = e.get("topics") or [], e["name"]
        if name in ("attester_added", "attester_reinstated"):
            ensure(topics[0]); status[topics[0]] = "active"
        elif name == "attester_suspended":
            ensure(topics[0]); status[topics[0]] = "suspended"
        elif name == "attester_removed":
            ensure(topics[0]); status[topics[0]] = "removed"
        elif name == "attestation_recorded":
            who = e.get("data") or ""
            if not who:
                continue
            ensure(who)
            if topics[0] not in history:
                order.append(topics[0])
            history.setdefault(topics[0], []).append(who)
        elif name == "attestation_revoked" and topics[0] in history:
            revoked.add(topics[0])
    return attesters, status, history, order, revoked


def render(events, regions):
    attesters, status, history, order, revoked = build(events, regions)
    out = ["# Generated by sandbox/replay.py. Do not edit by hand.",
           f"# Window: {len(events)} events, ledgers "
           f"{events[0]['ledger'] if events else '-'}..{events[-1]['ledger'] if events else '-'}\n"]
    for addr in sorted(attesters):
        out += ["[[attesters]]", f'name = "{name_of(addr)}"']
        if attesters[addr]:
            out.append(f'region = "{attesters[addr][:32]}"')
        out += [f'status = "{status[addr]}"', ""]
    for key, rows in (("attestations", [r for r in order if r not in revoked]),
                      ("revocations", [r for r in order if r in revoked])):
        for rec in rows:
            by = ", ".join(f'"{name_of(a)}"' for a in history[rec])
            out += [f"[[{key}]]", f'record = "{rec[:64]}"', f"by = [{by}]", ""]
    return "\n".join(out)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--events", required=True)
    p.add_argument("--from", dest="lo", type=int, required=True)
    p.add_argument("--to", dest="hi", type=int, required=True)
    p.add_argument("--attesters", help="JSON map attester address -> region")
    args = p.parse_args(argv)
    regions = {}
    if args.attesters:
        with open(args.attesters, encoding="utf-8") as f:
            regions = json.load(f)
    sys.stdout.write(render(load_window(args.events, args.lo, args.hi), regions) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
