#!/usr/bin/env python3
"""Render Mermaid sequence diagrams from recorded call traces.

Traces live in docs/architecture/traces/*.json (one flow each: actors plus
ordered steps of call / auth / event, as captured from integration test runs).
Output: docs/architecture/sequence-diagrams.md. `--check` fails if it is stale.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
TRACES = ROOT / "docs/architecture/traces"
OUT = ROOT / "docs/architecture/sequence-diagrams.md"


def render(trace):
    lines = ["sequenceDiagram"]
    lines += [f"    participant {a}" for a in trace["actors"]]
    for s in trace["steps"]:
        if "event" in s:
            lines.append(f"    Note over {s['from']}: event {s['event']}")
            continue
        auth = f" [auth: {s['auth']}]" if s.get("auth") else ""
        lines.append(f"    {s['from']}->>{s['to']}: {s['call']}{auth}")
    return "\n".join(lines)


def build():
    out = [
        "# Sequence diagrams",
        "",
        "<!-- GENERATED by scripts/gen_sequence_diagrams.py from docs/architecture/traces/*.json. Do not edit. -->",
        "",
    ]
    for path in sorted(TRACES.glob("*.json")):
        trace = json.loads(path.read_text())
        out += [f"## {trace['title']}", "", "```mermaid", render(trace), "```", ""]
    return "\n".join(out)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("sequence-diagrams.md is stale: run scripts/gen_sequence_diagrams.py")
        print("ok: sequence diagrams are fresh")
    else:
        OUT.write_text(text)
