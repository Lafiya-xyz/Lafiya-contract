#!/usr/bin/env python3
"""Generate (or check) the typed client for the indexer OpenAPI spec.

    python3 scripts/gen_indexer_client.py            # write packages/indexer-client/src/generated.ts
    python3 scripts/gen_indexer_client.py --check     # diff, don't write

Reads `crates/lafiya-indexer/openapi.yaml` and emits:

- `components` schemas as TypeScript interfaces (nullable -> `| null`,
  enums -> string literal unions, `$ref` -> interface name),
- one `paths` entry per operation with its method, path template, path/query
  parameters and the JSON response schema per status code.

The generated file is committed; CI runs `--check` so a spec change that is
not regenerated fails the build. Requires PyYAML.
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC_PATH = ROOT / "crates" / "lafiya-indexer" / "openapi.yaml"
OUT = ROOT / "packages" / "indexer-client" / "src" / "generated.ts"

HEADER = """// Generated by scripts/gen_indexer_client.py -- do not hand-edit.
// Regenerate with `python3 scripts/gen_indexer_client.py`.

"""

_SCALARS = {
    "string": "string",
    "integer": "number",
    "number": "number",
    "boolean": "boolean",
}


def resolve(spec, node):
    while isinstance(node, dict) and "$ref" in node:
        cur = spec
        for part in node["$ref"].lstrip("#/").split("/"):
            cur = cur[part]
        node = cur
    return node


def ref_name(node):
    return node["$ref"].rsplit("/", 1)[-1]


def ts_type(spec, node, indent=0):
    node = resolve(spec, node)
    if not isinstance(node, dict):
        return "unknown"
    if "$ref" in node:  # pragma: no cover - resolve() already followed it
        return ref_name(node)
    if "enum" in node:
        return " | ".join(_literal(v) for v in node["enum"])
    t = node.get("type")
    if t == "array":
        inner = ts_type(spec, node.get("items", {}), indent)
        out = f"{inner}[]" if " " not in inner else f"({inner})[]"
    elif t == "object" or "properties" in node:
        out = object_type(spec, node, indent)
    else:
        out = _SCALARS.get(t, "unknown")
    if node.get("nullable"):
        out = f"{out} | null"
    return out


def _literal(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return '"' + str(value).replace('"', '\\"') + '"'


def object_type(spec, node, indent=0):
    props = node.get("properties") or {}
    if not props:
        return "Record<string, unknown>"
    required = set(node.get("required") or [])
    pad = "  " * (indent + 1)
    lines = ["{"]
    for name, prop in props.items():
        opt = "" if name in required else "?"
        lines.append(f"{pad}{name}{opt}: {ts_type(spec, prop, indent + 1)};")
    lines.append("  " * indent + "}")
    return "\n".join(lines)


def schema_name(node):
    """Name of the interface a schema node maps to, if it is a plain $ref."""
    return ref_name(node) if isinstance(node, dict) and "$ref" in node else None


def emit_schemas(spec):
    out = []
    for name, node in (spec.get("components", {}).get("schemas") or {}).items():
        node = resolve(spec, node)
        if node.get("type") == "string" and "enum" not in node:
            out.append(f"export type {name} = string;\n")
            continue
        out.append(f"export interface {name} {object_type(spec, node)}\n")
    return out


def emit_operations(spec):
    out = []
    for path, item in (spec.get("paths") or {}).items():
        shared = item.get("parameters") or []
        for method, op in item.items():
            if method not in ("get", "post", "put", "patch", "delete"):
                continue
            op_id = op.get("operationId") or _operation_id(method, path)
            params = list(shared) + list(op.get("parameters") or [])
            path_params, query_params = [], []
            for p in params:
                p = resolve(spec, p)
                entry = (p["name"], ts_type(spec, p.get("schema", {})))
                (path_params if p.get("in") == "path" else query_params).append(entry)
            responses = {}
            for status, resp in (op.get("responses") or {}).items():
                resp = resolve(spec, resp)
                schema = (
                    resp.get("content", {})
                    .get("application/json", {})
                    .get("schema")
                )
                if schema is not None:
                    responses[status] = ts_type(spec, schema)
            out.append(
                "  {\n"
                f'    operationId: "{op_id}",\n'
                f'    method: "{method.upper()}",\n'
                f'    path: "{path}",\n'
                f"    pathParams: {_tuple_list(path_params)},\n"
                f"    queryParams: {_tuple_list(query_params)},\n"
                f"    responses: {_response_map(responses)},\n"
                "  },"
            )
    return out


def _operation_id(method, path):
    parts = [p for p in path.strip("/").split("/") if p]
    words = [method]
    for part in parts:
        if part.startswith("{") and part.endswith("}"):
            words.append("by_" + part[1:-1])
        else:
            words.append(part.replace("-", "_"))
    return "_".join(words)


def _tuple_list(entries):
    if not entries:
        return "[]"
    inner = ", ".join(f'["{n}", "{t}"]' for n, t in entries)
    return f"[{inner}]"


def _response_map(responses):
    if not responses:
        return "{}"
    inner = ", ".join(f'"{s}": {t}' for s, t in responses.items())
    return "{ " + inner + " }"


def render(spec):
    parts = [HEADER]
    parts.extend(emit_schemas(spec))
    parts.append(
        "/** One HTTP operation of the indexer API. */\n"
        "export interface OperationSpec {\n"
        "  operationId: string;\n"
        '  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";\n'
        "  path: string;\n"
        "  pathParams: [string, string][];\n"
        "  queryParams: [string, string][];\n"
        "  responses: Record<string, string>;\n"
        "}\n"
    )
    parts.append("export const OPERATIONS = [\n" + "\n".join(emit_operations(spec)) + "\n] as const;\n")
    return "\n".join(parts)


def main(argv):
    spec = yaml.safe_load(SPEC_PATH.read_text())
    text = render(spec)
    if "--check" in argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run scripts/gen_indexer_client.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
