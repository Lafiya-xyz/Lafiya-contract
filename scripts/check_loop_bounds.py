#!/usr/bin/env python3
"""Require an annotated bound on every loop/iterator in non-test contract code.

Each loop needs a `// loop-bound: <BOUND> -- <worst case>` comment within the
5 lines above it. <BOUND> is one of:
  * a `const NAME` defined in the same file (must exist),
  * LOCAL            - length validated immediately before the loop,
  * ACCEPTED(<who>)  - unbounded by a constant, with the justification text.

  python3 scripts/check_loop_bounds.py           # fail on unannotated loops / stale report
  python3 scripts/check_loop_bounds.py --write   # regenerate docs/security/loop-bounds.md
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPORT = ROOT / "docs" / "security" / "loop-bounds.md"
LOOP = re.compile(r"^\s*(for\s|while\s|loop\s*\{)|\.(any|all|position|fold|for_each)\(")
ANNOT = re.compile(r"//\s*loop-bound:\s*(\S+?)\s*--\s*(.+)$")
LOOKBACK = 5


def scan(path):
    """Yield (line_no, source, bound, note) for every loop; bound is None if missing."""
    lines = path.read_text().split("\n")
    end = next((i for i, l in enumerate(lines) if "#[cfg(test)]" in l), len(lines))
    src = "\n".join(lines)
    for i, line in enumerate(lines[:end]):
        if line.lstrip().startswith("//") or not LOOP.search(line):
            continue
        bound = note = None
        for j in range(i - 1, max(i - 1 - LOOKBACK, -1), -1):
            m = ANNOT.search(lines[j])
            if m:
                bound, note = m.group(1), m.group(2)
                break
        if bound and not (
            bound == "LOCAL"
            or bound.startswith("ACCEPTED(")
            or re.search(rf"\bconst\s+{re.escape(bound)}\b", src)
        ):
            bound = None  # names a constant that does not exist
        yield i + 1, line.strip(), bound, note


def main():
    rows, errors = [], []
    for path in sorted((ROOT / "contracts").glob("*/src/lib.rs")):
        rel = path.relative_to(ROOT).as_posix()
        for n, text, bound, note in scan(path):
            if bound is None:
                errors.append(f"{rel}:{n}: missing or invalid `// loop-bound:` for `{text}`")
            else:
                rows.append((rel, n, text, bound, note))
    out = ["# Loop bounds", "",
           "Generated by `scripts/check_loop_bounds.py --write`; CI fails if it is stale.",
           "Every loop over a storage-derived or caller-supplied collection must carry a",
           "`// loop-bound:` annotation naming an enforced constant, or be explicitly",
           "`ACCEPTED(...)` with a justification.", "",
           "| Location | Loop | Bound | Worst case / justification |", "|---|---|---|---|"]
    for rel, n, text, bound, note in rows:
        loop = text.replace("|", "\\|")
        out.append(f"| `{rel}:{n}` | `{loop}` | `{bound}` | {note} |")
    accepted = [r for r in rows if r[3].startswith("ACCEPTED(")]
    out += ["", f"{len(rows)} loops; {len(accepted)} accepted without a constant bound.", ""]
    report = "\n".join(out)
    if "--write" in sys.argv:
        REPORT.parent.mkdir(parents=True, exist_ok=True)
        REPORT.write_text(report)
    elif not REPORT.exists() or REPORT.read_text() != report:
        errors.append(f"{REPORT.relative_to(ROOT)} is stale; run with --write")
    for e in errors:
        print(e, file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
