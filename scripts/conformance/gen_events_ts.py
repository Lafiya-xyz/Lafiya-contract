#!/usr/bin/env python3
"""Generate (or check) `packages/events/src/generated.ts`, the typed event
decoder table for `@lafiya/events`, from the committed interface snapshots.

    python3 scripts/conformance/gen_events_ts.py            # write generated.ts
    python3 scripts/conformance/gen_events_ts.py --check     # diff, don't write

The snapshots in `snapshots/` are themselves checked against the built Wasm
by `check_snapshot.py`, so a new or changed `#[contractevent]` that lands
without regenerating the snapshot *and* this file fails CI. Reading the
snapshots (rather than the Wasm) lets the drift check run without the
`stellar` CLI or a contract build.

Contracts in `contracts.py` with no `event_v0` entries (e.g. the multisig
account today) contribute no decoders; adding events to them only needs a
snapshot entry in `contracts.py`.

The incentive-pool contract is included like any other contract: every
`event_v0` in `snapshots/incentive-pool.json` becomes a payload interface, an
`EVENT_SPECS` entry (with all of its payload versions, newest first) and an
`EVENT_CONTRACTS` entry. `packages/events/src/spec.ts` re-exports the
generated `EventKind`/`EventPayloads`/`EVENT_SPECS`/`EVENT_CONTRACTS` tables,
so pool events are decodable through `@lafiya/events` without hand edits.
"""
import json
import sys

from contracts import CONTRACTS, REPO_ROOT, SNAPSHOT_DIR

OUT = REPO_ROOT / "packages" / "events" / "src" / "generated.ts"
SPEC = REPO_ROOT / "packages" / "events" / "src" / "spec.ts"

HEADER = """// Generated by scripts/conformance/gen_events_ts.py -- do not hand-edit.
// Regenerate with `python3 scripts/conformance/gen_events_ts.py`.

import type { EventSpec } from "./spec.js";
"""

_TS_SCALARS = {
    "address": "string",
    "bool": "boolean",
    "bytes": "string",
    "i32": "number",
    "u32": "number",
    "i64": "bigint",
    "u64": "bigint",
    "i128": "bigint",
    "u128": "bigint",
    "i256": "bigint",
    "u256": "bigint",
    "timepoint": "bigint",
    "duration": "bigint",
    "string": "string",
    "symbol": "string",
    "void": "null",
}


def ts_type(t):
    if isinstance(t, str):
        return _TS_SCALARS.get(t, "unknown")
    ((kind, body),) = t.items()
    if kind == "bytes_n":
        return "string"
    if kind == "option":
        return f"{ts_type(body['value_type'])} | undefined"
    if kind == "vec":
        return f"Array<{ts_type(body['element_type'])}>"
    return "unknown"


def camel(name):
    head, *rest = name.split("_")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def load_events():
    """{event name: [(contract, spec), ...]} across every contract.

    Includes the incentive-pool contract so its events get decoders alongside
    the registries and multisig.
    """
    events = {}
    for contract in sorted(CONTRACTS):
        path = SNAPSHOT_DIR / f"{contract}.json"
        if not path.exists():
            continue
        for entry in json.loads(path.read_text()):
            if entry["kind"] == "event_v0":
                events.setdefault(entry["spec"]["name"], []).append((contract, entry["spec"]))
    return events


def payload_versions(specs):
    """Distinct payload shapes for one event kind, newest first.

    Snapshots list an event's versions newest first; dedupe by literal while
    preserving that order so historical payloads keep decoding.
    """
    seen = set()
    versions = []
    for _, spec in specs:
        literal = spec_literal(spec)
        if literal not in seen:
            seen.add(literal)
            versions.append(literal)
    return versions


def spec_literal(spec):
    fields = [
        {
            "name": p["name"],
            "key": camel(p["name"]),
            "type": p.get("type_", p.get("type")),
            "location": "topic" if p["location"] == "topic_list" else "data",
        }
        for p in spec["params"]
    ]
    return json.dumps(
        {
            "prefixTopics": spec["prefix_topics"],
            "dataFormat": spec["data_format"],
            "fields": fields,
        },
        sort_keys=True,
    )


def render():
    events = load_events()
    out = [HEADER]

    kinds = sorted(events)
    out.append("/** Every event kind emitted by a Lafiya contract. */")
    out.append("export type EventKind =")
    out.append("\n".join(f'  | "{k}"' for k in kinds) + ";\n")

    for kind in kinds:
        specs = events[kind]
        # Same-named events must agree across contracts to share one type.
        distinct = {spec_literal(s) for _, s in specs}
        if len(distinct) != 1:
            sys.exit(f"error: event {kind} has different shapes across contracts")
        _, spec = specs[0]
        out.append(f"export interface {kind}Payload {{")
        for p in spec["params"]:
            out.append(f"  {camel(p['name'])}: {ts_type(p.get('type_', p.get('type')))};")
        out.append("}\n")

        # Emit a payload interface per historical version so decoders can
        # narrow to the shape that actually matched.
        versions = payload_versions(specs)
        for i, literal in enumerate(versions[1:], start=2):
            version_spec = json.loads(literal)
            out.append(f"export interface {kind}PayloadV{i} {{")
            for p in version_spec["fields"]:
                out.append(f"  {p['key']}: {ts_type(p['type'])};")
            out.append("}\n")

    out.append("/** Decoded payload type for each event kind. */")
    out.append("export interface EventPayloads {")
    for kind in kinds:
        out.append(f"  {kind}: {kind}Payload;")
    out.append("}\n")

    out.append("/**")
    out.append(" * Payload versions per event kind, newest first. A decoder tries each in")
    out.append(" * order, so an event that gains a field keeps decoding historical payloads")
    out.append(" * once the old shape is kept here under the event-versioning convention.")
    out.append(" */")
    out.append("export const EVENT_SPECS: Record<EventKind, readonly EventSpec[]> = {")
    for kind in kinds:
        versions = payload_versions(events[kind])
        out.append(f"  {kind}: [{', '.join(versions)}],")
    out.append("};\n")

    out.append("/** Contracts that emit each event kind. */")
    out.append("export const EVENT_CONTRACTS: Record<EventKind, readonly string[]> = {")
    for kind in kinds:
        names = json.dumps(sorted({c for c, _ in events[kind]}))
        out.append(f"  {kind}: {names},")
    out.append("};")
    return "\n".join(out) + "\n"


def check_spec():
    """`spec.ts` must re-export the generated tables so pool events are public."""
    if not SPEC.exists():
        return f"[events-ts] {SPEC} is missing -- it must re-export the generated tables"
    text = SPEC.read_text()
    missing = [
        name
        for name in ("EventKind", "EventPayloads", "EVENT_SPECS", "EVENT_CONTRACTS")
        if name not in text
    ]
    if missing:
        return f"[events-ts] {SPEC} does not re-export {', '.join(missing)}"
    return None


def main():
    rendered = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != rendered:
            print(f"[events-ts] {OUT} is stale -- run `python3 scripts/conformance/gen_events_ts.py`")
            sys.exit(1)
        problem = check_spec()
        if problem:
            print(problem)
            sys.exit(1)
        print(f"[events-ts] OK -- {OUT.name} matches the interface snapshots")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(rendered)
    print(f"[events-ts] wrote {OUT}")


if __name__ == "__main__":
    main()
