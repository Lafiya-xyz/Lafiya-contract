fn doc(v: &Value) -> String {
    v["doc"].as_str().unwrap_or_default().replace("\\n", "\n")
}

fn ty(t: &Value) -> String {
    if let Some(s) = t.as_str() {
        return match s {
            "address" => "Address",
            "bool" => "bool",
            "void" => "()",
            "error" => "Error",
            "symbol" => "Symbol",
            "string" => "String",
            "bytes" => "Bytes",
            "u32" => "u32",
            "i32" => "i32",
            "u64" => "u64",
            "i64" => "i64",
            "u128" => "u128",
            "i128" => "i128",
            "timepoint" => "Timepoint",
            "duration" => "Duration",
            "val" => "Val",
            other => other,
        }
        .to_string();
    }
    let (kind, v) = t
        .as_object()
        .and_then(|o| o.iter().next())
        .expect("type is a string or single-key object");
    match kind.as_str() {
        "option" => format!("Option<{}>", ty(&v["value_type"])),
        "result" => format!("Result<{}, {}>", ty(&v["ok_type"]), ty(&v["error_type"])),
        "vec" => format!("Vec<{}>", ty(&v["element_type"])),
        "map" => format!("Map<{}, {}>", ty(&v["key_type"]), ty(&v["value_type"])),
        "bytes_n" => format!("BytesN<{}>", v["n"]),
        "udt" => v["name"].as_str().unwrap_or_default().to_string(),
        "tuple" => format!(
            "({})",
            v["value_types"]
                .as_array()
                .map(|a| a.iter().map(ty).collect::<Vec<_>>().join(", "))
                .unwrap_or_default()
        ),
        other => other.to_string(),
    }
}

fn cell(s: &str) -> String {
    s.replace('\n', " ").replace('|', "\\|")
}

fn contract_page(name: &str, spec: &Value) -> String {
    let entries = spec.as_array().cloned().unwrap_or_default();
    let of = |kind: &str| -> Vec<Value> {
        entries
            .iter()
            .filter_map(|e| e.get(kind).cloned())
            .collect()
    };
    let mut out = String::from(HEADER);
    let _ = writeln!(out, "# `{name}`\n");
    let _ = writeln!(
        out,
        "Interface reference generated from the contract spec embedded in `{}.wasm`. \
         See the contract's hand-written docs for design context.\n",
        name.replace('-', "_")
    );

    let _ = writeln!(out, "## Functions\n");
    let mut fns = of("function_v0");
    fns.sort_by(|a, b| a["name"].as_str().cmp(&b["name"].as_str()));
    for f in &fns {
        let inputs: Vec<String> = f["inputs"]
            .as_array()
            .into_iter()
            .flatten()
            .map(|i| {
                format!(
                    "{}: {}",
                    i["name"].as_str().unwrap_or_default(),
                    ty(&i["type_"])
                )
            })
            .collect();
        let output = f["outputs"]
            .as_array()
            .and_then(|o| o.first())
            .map(|o| format!(" -> {}", ty(o)))
            .unwrap_or_default();
        let name = f["name"].as_str().unwrap_or_default();
        let _ = writeln!(out, "### `{name}`\n");
        let _ = writeln!(
            out,
            "```rust\nfn {name}({}){output}\n```\n",
            inputs.join(", ")
        );
        let d = doc(f);
        if !d.is_empty() {
            let _ = writeln!(out, "{d}\n");
        }
    }

    let structs = of("udt_struct_v0");
    if !structs.is_empty() {
        let _ = writeln!(out, "## Types\n");
        for s in &structs {
            let _ = writeln!(out, "### `{}`\n", s["name"].as_str().unwrap_or_default());
            let d = doc(s);
            if !d.is_empty() {
                let _ = writeln!(out, "{d}\n");
            }
            let _ = writeln!(out, "| Field | Type | Description |\n| --- | --- | --- |");
            for f in s["fields"].as_array().into_iter().flatten() {
                let _ = writeln!(
                    out,
                    "| `{}` | `{}` | {} |",
                    f["name"].as_str().unwrap_or_default(),
                    ty(&f["type_"]),
                    cell(&doc(f))
                );
            }
            out.push('\n');
        }
    }

    for e in of("udt_error_enum_v0") {
        let _ = writeln!(
            out,
            "## Errors (`{}`)\n",
            e["name"].as_str().unwrap_or_default()
        );
        let _ = writeln!(out, "| Code | Name | Description |\n| --- | --- | --- |");
        for c in e["cases"].as_array().into_iter().flatten() {
            let _ = writeln!(
                out,
                "| {} | `{}` | {} |",
                c["value"],
                c["name"].as_str().unwrap_or_default(),
                cell(&doc(c))
            );
        }
        out.push('\n');
    }

    let mut events = of("event_v0");
    if !events.is_empty() {
        events.sort_by(|a, b| a["name"].as_str().cmp(&b["name"].as_str()));
        let _ = writeln!(out, "## Events\n");
        let _ = writeln!(
            out,
            "| Event | Topics | Data | Description |\n| --- | --- | --- | --- |"
        );
        for e in &events {
            let mut topics: Vec<String> = e["prefix_topics"]
                .as_array()
                .into_iter()
                .flatten()
                .map(|t| format!("`\"{}\"`", t.as_str().unwrap_or_default()))
                .collect();
            let mut data = Vec::new();
            for p in e["params"].as_array().into_iter().flatten() {
                let field = format!(
                    "`{}: {}`",
                    p["name"].as_str().unwrap_or_default(),
                    ty(&p["type_"])
                );
                if p["location"] == "topic_list" {
                    topics.push(field);
                } else {
                    data.push(field);
                }
            }
            let _ = writeln!(
                out,
                "| `{}` | {} | {} | {} |",
                e["name"].as_str().unwrap_or_default(),
                topics.join(", "),
                data.join(", "),
                cell(&doc(e))
            );
        }
        out.push('\n');
    }
    out.trim_end().to_string() + "\n"
}

// ---------------------------------------------------------------------------
// CLI reference (from clap's --help output)
// ---------------------------------------------------------------------------

fn help(cargo_args: &[&str], path: &[String]) -> Result<String> {
    let out = Command::new("cargo")
        .args(cargo_args)
        .args(path)
        .arg("--help")
        .output()?;
    if !out.status.success() {
        bail!("{}", String::from_utf8_lossy(&out.stderr).trim());
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim_end().to_string())
}

/// Subcommand names listed under clap's "Commands:" heading.
fn subcommands(help: &str) -> Vec<String> {
    help.lines()
        .skip_while(|l| !l.starts_with("Commands:"))
        .skip(1)
        .take_while(|l| l.starts_with("  "))
        .filter_map(|l| l.split_whitespace().next())
        .filter(|c| *c != "help")
        .map(str::to_string)
        .collect()
}

fn cli_page(display: &str, cargo_args: &[&str]) -> String {
    let mut out = String::from(HEADER);
    let _ = writeln!(out, "# `{display}`\n");
    let mut queue = vec![Vec::<String>::new()];
    while let Some(path) = queue.pop() {
        let text = match help(cargo_args, &path) {
            Ok(t) => t,
            Err(_) => {
                // Keep the site building while the binary doesn't compile; the
                // notice changes (and --check fails) as soon as it builds again.
                eprintln!("warning: `{display}` did not build; its reference is a placeholder");
                let _ = writeln!(
                    out,
                    "> **Not generated:** `{display}` did not build when this page was \
                     generated. Fix the build and rerun `cargo xtask docs`."
                );
                return out;
            }
        };
        let title = if path.is_empty() {
            display.to_string()
        } else {
            format!("{display} {}", path.join(" "))
        };
        if !path.is_empty() {
            let _ = writeln!(out, "## `{title}`\n");
        }
        let _ = writeln!(out, "```text\n{text}\n```\n");
        for sub in subcommands(&text).into_iter().rev() {
            let mut p = path.clone();
            p.push(sub);
            queue.push(p);
        }
    }
    out.trim_end().to_string() + "\n"
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_nested_types() {
        let t: Value = serde_json::json!({"result": {"ok_type": {"option": {"value_type": {"udt": {"name": "Attestation"}}}}, "error_type": "error"}});
        assert_eq!(ty(&t), "Result<Option<Attestation>, Error>");
        assert_eq!(ty(&serde_json::json!({"bytes_n": {"n": 32}})), "BytesN<32>");
    }

    #[test]
    fn rewrites_links_leaving_the_site() {
        let r = |t, repo, site| rewrite_target(t, repo, site).unwrap();
        assert_eq!(
            r(
                "../../contracts/a/src/lib.rs#L1",
                "docs/adr/x.md",
                "adr/x.md"
            ),
            "https://github.com/Lafiya-xyz/Lafiya-contract/blob/main/contracts/a/src/lib.rs#L1"
        );
        assert_eq!(
            r("../glossary.md", "docs/adr/x.md", "adr/x.md"),
            "../glossary.md"
        );
        assert_eq!(
            r("../../PUBLISHING.md", "docs/adr/x.md", "adr/x.md"),
            "../imported/publishing.md"
        );
        assert_eq!(
            r(
                "README.md#getting-started",
                "CONTRIBUTING.md",
                "imported/contributing.md"
            ),
            "../overview.md#getting-started"
        );
        assert_eq!(
            r(
                "docs/releasing.md",
                "CONTRIBUTING.md",
                "imported/contributing.md"
            ),
            "../releasing.md"
        );
        assert_eq!(
            r(
                "../../security/advisories/new",
                "SECURITY.md",
                "imported/security.md"
            ),
            "https://github.com/Lafiya-xyz/Lafiya-contract/security/advisories/new"
        );
        assert_eq!(rewrite_target("#x", "a.md", "a.md"), None);
        assert_eq!(rewrite_target("https://x.org", "a.md", "a.md"), None);
    }

    #[test]
    fn leaves_code_fences_alone() {
        let text = "```\n[a](../../x)\n```\n[b](../../y)\n";
        let out = rewrite_links(text, "docs/adr/z.md", "adr/z.md");
        assert!(out.contains("[a](../../x)"));
        assert!(out.contains("[b](https://github.com/Lafiya-xyz/Lafiya-contract/blob/main/y)"));
    }

    #[test]
    fn finds_subcommands() {
        let h = "About\n\nUsage: x <COMMAND>\n\nCommands:\n  up    Start\n  down  Stop\n  help  Print\n\nOptions:\n  -h";
        assert_eq!(subcommands(h), vec!["up", "down"]);
    }
}
