//! `cargo xtask docs`: generate the contract and CLI reference pages of the
//! documentation site (`--check` fails if the committed pages have drifted),
//! then stage the mdBook source in `target/book-src`.
//!
//! Staging copies `docs/`, imports the Markdown files that live elsewhere in
//! the repository (`IMPORTS`), and rewrites links that leave the site to point
//! at GitHub, so authored docs keep working both on GitHub and in the site.

use anyhow::{bail, Context, Result};
use serde_json::Value;
use std::fmt::Write as _;
use std::path::Path;
use std::process::Command;

const CONTRACTS: [&str; 3] = [
    "attester-registry",
    "attestation-registry",
    "multisig-account",
];
const CONTRACT_DIR: &str = "docs/reference/contracts";
const CLI_DIR: &str = "docs/reference/cli";
const STAGE_DIR: &str = "target/book-src";
const REPO_URL: &str = "https://github.com/Lafiya-xyz/Lafiya-contract";
/// Markdown outside `docs/` rendered in the site: (repository path, site path).
const IMPORTS: [(&str, &str); 12] = [
    ("SECURITY.md", "imported/security.md"),
    ("sandbox/README.md", "imported/sandbox.md"),
    (
        "verification/tla/README.md",
        "imported/formal-verification.md",
    ),
    ("CONTRIBUTING.md", "imported/contributing.md"),
    ("PUBLISHING.md", "imported/publishing.md"),
    ("CHANGELOG.md", "imported/changelog.md"),
    ("config/README.md", "imported/config.md"),
    ("scripts/README.md", "imported/scripts.md"),
    (
        "crates/lafiya-commitment/README.md",
        "imported/lafiya-commitment.md",
    ),
    (
        "crates/lafiya-rpc-resilience/README.md",
        "imported/lafiya-rpc-resilience.md",
    ),
    (
        "bindings/attester-registry/README.md",
        "imported/bindings-attester-registry.md",
    ),
    (
        "bindings/attestation-registry/README.md",
        "imported/bindings-attestation-registry.md",
    ),
];
const HEADER: &str =
    "<!-- GENERATED by `cargo xtask docs`. Do not edit; edit the source and regenerate. -->\n\n";

pub fn run(check: bool) -> Result<()> {
    let mut pages = Vec::new();
    build_wasm()?;
    for c in CONTRACTS {
        let wasm = format!("target/wasm32v1-none/release/{}.wasm", c.replace('-', "_"));
        let bytes = std::fs::read(&wasm).with_context(|| format!("reading {wasm}"))?;
        let spec = soroban_spec::read::from_wasm(&bytes)
            .map_err(|e| anyhow::anyhow!("reading contract spec from {wasm}: {e}"))?;
        let spec = serde_json::to_value(&spec)?;
        pages.push((format!("{CONTRACT_DIR}/{c}.md"), contract_page(c, &spec)));
    }
    pages.push((
        format!("{CLI_DIR}/lafiya-cli.md"),
        cli_page("lafiya-cli", &["run", "-q", "-p", "lafiya-cli", "--"]),
    ));
    pages.push((
        format!("{CLI_DIR}/xtask.md"),
        cli_page("cargo xtask", &["run", "-q", "-p", "xtask", "--"]),
    ));

    let mut drifted = Vec::new();
    for (path, body) in &pages {
        let current = std::fs::read_to_string(path).unwrap_or_default();
        if current == *body {
            continue;
        }
        if check {
            drifted.push(path.as_str());
        } else {
            std::fs::create_dir_all(Path::new(path).parent().expect("has parent"))?;
            std::fs::write(path, body)?;
            println!("wrote {path}");
        }
    }
    if !drifted.is_empty() {
        bail!(
            "generated reference is out of date: {}\nrun `cargo xtask docs` and commit the result",
            drifted.join(", ")
        );
    }
    stage()?;
    println!("staged mdBook source in {STAGE_DIR}");
    Ok(())
}

fn build_wasm() -> Result<()> {
    let mut cmd = Command::new("cargo");
    cmd.args(["build", "--release", "--target", "wasm32v1-none"]);
    for c in CONTRACTS {
        cmd.args(["-p", c]);
    }
    if !cmd.status()?.success() {
        bail!("building contract wasm failed");
    }
    Ok(())
}

