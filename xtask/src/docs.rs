// Staging
// ---------------------------------------------------------------------------

fn stage() -> Result<()> {
    let _ = std::fs::remove_dir_all(STAGE_DIR);
    copy_dir(Path::new("docs"), Path::new(STAGE_DIR))?;
    // Book configuration and theme are read from docs/, not the source dir.
    std::fs::remove_file(Path::new(STAGE_DIR).join("book.toml"))?;
    std::fs::remove_dir_all(Path::new(STAGE_DIR).join("theme"))?;
    for (src, dest) in IMPORTS {
        let text = std::fs::read_to_string(src).with_context(|| format!("reading {src}"))?;
        let out = Path::new(STAGE_DIR).join(dest);
        std::fs::create_dir_all(out.parent().expect("has parent"))?;
        std::fs::write(out, rewrite_links(&text, src, dest))?;
    }
    Ok(())
}

fn copy_dir(from: &Path, to: &Path) -> Result<()> {
    std::fs::create_dir_all(to)?;
    for entry in std::fs::read_dir(from)? {
        let entry = entry?;
        let (src, dest) = (entry.path(), to.join(entry.file_name()));
        if entry.file_type()?.is_dir() {
            copy_dir(&src, &dest)?;
        } else if src.extension().is_some_and(|e| e == "md") {
            let text = std::fs::read_to_string(&src)?;
            let repo_path = src.to_string_lossy().replace('\\', "/");
            let site_path = repo_path.trim_start_matches("docs/").to_string();
            let mut text = rewrite_links(&text, &repo_path, &site_path);
            if site_path == "adr/README.md" {
                text = status_badges(&text);
            }
            std::fs::write(&dest, text)?;
        } else {
            std::fs::copy(&src, &dest)?;
        }
    }
    Ok(())
}

/// Render the Status column of the ADR index as badges.
fn status_badges(text: &str) -> String {
    text.lines()
        .map(|line| {
            let Some(cell) = line.strip_suffix(" |").and_then(|l| l.rsplit_once("| ")) else {
                return line.to_string();
            };
            let status = cell.1.trim();
            let class = status
                .split_whitespace()
                .next()
                .unwrap_or_default()
                .to_lowercase();
            if ["accepted", "proposed", "deprecated", "superseded"].contains(&class.as_str()) {
                format!(
                    "{}| <span class=\"adr-status {class}\">{status}</span> |",
                    cell.0
                )
            } else {
                line.to_string()
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
        + "\n"
}

/// Normalize `base_dir/target` into repository-relative components; `Err(n)`
/// if it climbs `n` levels above the repository root.
fn resolve(base_dir: &str, target: &str) -> std::result::Result<Vec<String>, usize> {
    let mut parts: Vec<String> = Vec::new();
    let mut above = 0;
    for c in base_dir.split('/').chain(target.split('/')) {
        match c {
            "" | "." => {}
            ".." => {
                if parts.pop().is_none() {
                    above += 1;
                }
            }
            c => parts.push(c.to_string()),
        }
    }
    if above > 0 {
        Err(above)
    } else {
        Ok(parts)
    }
}

fn dir_of(path: &str) -> &str {
    path.rsplit_once('/').map_or("", |(d, _)| d)
}

/// Relative link from the page at `from` to `to` (both site paths).
fn relative(from: &str, to: &str) -> String {
    let depth = dir_of(from).split('/').filter(|c| !c.is_empty()).count();
    "../".repeat(depth) + to
}

/// Where a link written in the file at `repo_path` should point once that
/// file is served at `site_path`.
fn rewrite_target(target: &str, repo_path: &str, site_path: &str) -> Option<String> {
    if target.is_empty()
        || target.starts_with('#')
        || target.contains("://")
        || target.starts_with("mailto:")
    {
        return None;
    }
    let (path, anchor) = target.split_once('#').map_or((target, ""), |(p, a)| (p, a));
    let anchor = if anchor.is_empty() {
        String::new()
    } else {
        format!("#{anchor}")
    };
    let parts = match resolve(dir_of(repo_path), path) {
        Ok(parts) => parts,
        Err(above) => {
            // Links such as `../../security/advisories/new` are relative to
            // the file's GitHub URL (`<repo>/blob/main/...`).
            let base = ["blob", "main"];
            let keep = base.len().checked_sub(above)?;
            let prefix = base[..keep].join("/");
            let rest = path.trim_start_matches("../").trim_start_matches("./");
            let url = [REPO_URL, &prefix, rest]
                .iter()
                .filter(|s| !s.is_empty())
                .copied()
                .collect::<Vec<_>>()
                .join("/");
            return Some(url + &anchor);
        }
    };
    let joined = parts.join("/");
    if let Some(inside) = joined.strip_prefix("docs/") {
        return Some(relative(site_path, inside) + &anchor);
    }
    if joined == "README.md" {
        return Some(relative(site_path, "overview.md") + &anchor);
    }
    if let Some((_, dest)) = IMPORTS.iter().find(|(src, _)| *src == joined) {
        return Some(relative(site_path, dest) + &anchor);
    }
    Some(format!("{REPO_URL}/blob/main/{joined}{anchor}"))
}

/// Rewrite every inline Markdown link target `](...)`, outside code fences.
fn rewrite_links(text: &str, repo_path: &str, site_path: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut in_fence = false;
    for line in text.split_inclusive('\n') {
        if line.trim_start().starts_with("```") {
            in_fence = !in_fence;
        }
        if in_fence {
            out.push_str(line);
            continue;
        }
        let mut rest = line;
        while let Some(i) = rest.find("](") {
            out.push_str(&rest[..i + 2]);
            rest = &rest[i + 2..];
            let Some(end) = rest.find(')') else { break };
            let target = &rest[..end];
            match rewrite_target(target, repo_path, site_path) {
                Some(t) => out.push_str(&t),
                None => out.push_str(target),
            }
            rest = &rest[end..];
        }
        out.push_str(rest);
    }
    out
}

